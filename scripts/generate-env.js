// Writes src/environments/environment.<target>.ts from process.env, which
// dotenv-cli has already populated from .env.staging / .env.production.
// Run via `npm run build:staging` / `npm run build:prod` — not meant to be
// called directly. The output file is gitignored and never committed; the
// required shape/keys are documented in .env.staging.example / .env.production.example.
const fs = require('fs');
const path = require('path');

const target = process.argv[2]; // 'staging' | 'production'
const files = {
  staging: { output: 'environment.staging.ts', envFile: '.env.staging' },
  production: { output: 'environment.prod.ts', envFile: '.env.production' }
}[target];

if (!files) {
  console.error(`Unknown target "${target}". Expected "staging" or "production".`);
  process.exit(1);
}

const required = [
  'API_URL',
  'FIREBASE_API_KEY',
  'FIREBASE_AUTH_DOMAIN',
  'FIREBASE_PROJECT_ID',
  'FIREBASE_STORAGE_BUCKET',
  'FIREBASE_MESSAGING_SENDER_ID',
  'FIREBASE_APP_ID'
];

// Storage secrets belong only on the API projects (RULES.md §3, F9-S19 / D48). The UI talks to storage only
// through short-lived links from the API, so it never needs these. On a hosted build, stop if any is set on the
// UI project. Only the names are printed, never the values.
if (process.env.VERCEL) {
  const storageSecret = name =>
    ['AWS_ACCESS_KEY_ID', 'AWS_SECRET_ACCESS_KEY', 'AWS_SESSION_TOKEN', 'SUPABASE_SERVICE_ROLE_KEY', 'SUPABASE_URL'].includes(name)
    || /(^|_)S3(_|$)/.test(name);
  const found = Object.keys(process.env).filter(storageSecret);
  if (found.length) {
    console.error(
      `These storage settings are on the UI's Vercel project: ${found.join(', ')}.\n` +
      `Everything in the UI build is public, and the UI never needs them. Remove them from the nb-ecom-ui project ` +
      `(Settings → Environment Variables); they belong only on the Care API project. Then redeploy.`
    );
    process.exit(1);
  }
}

const missing = required.filter(key => !process.env[key]);
if (missing.length) {
  console.error(
    `Missing env vars for "${target}" build: ${missing.join(', ')}\n` +
    `Copy ${files.envFile}.example to ${files.envFile} and fill them in.`
  );
  process.exit(1);
}

// Production must never silently ship with the local-dev mock Firebase config —
// that config is what makes FirebaseAuthService fall into its dev-simulation mode
// (fake users, OTP always "123456"), which would be a real-world auth bypass in prod.
const KNOWN_PLACEHOLDER_KEYS = ['YOUR_FIREBASE_API_KEY'];
if (target === 'production' && KNOWN_PLACEHOLDER_KEYS.includes(process.env.FIREBASE_API_KEY)) {
  console.error(
    `FIREBASE_API_KEY in .env.production is still the placeholder value ("${process.env.FIREBASE_API_KEY}").\n` +
    `Production builds must use a real Firebase project's Web SDK config — see .env.production.example.`
  );
  process.exit(1);
}

// On a hosted build (Vercel sets VERCEL=1), API_URL must be a public HTTPS API. A localhost or http:// URL,
// or the website's own domain (Vercel only serves the UI there), deploys a site where every sign-in fails
// right after Firebase. Local `ng serve -c production` against localhost is unaffected.
if (target === 'production' && process.env.VERCEL) {
  const apiUrl = process.env.API_URL;
  let problem = null;
  let host = '';
  try { host = new URL(apiUrl).hostname; } catch { problem = 'is not a valid URL'; }
  const vercelJson = path.join(__dirname, '..', 'vercel.json');
  const proxiesApi = fs.existsSync(vercelJson) && /"source"\s*:\s*"\/api\//.test(fs.readFileSync(vercelJson, 'utf8'));
  if (!problem && !apiUrl.startsWith('https://')) problem = 'must start with https://';
  else if (!problem && ['localhost', '127.0.0.1'].includes(host)) problem = 'points at localhost, which is each visitor\'s own computer';
  else if (!problem && !proxiesApi && /(^|\.)narturebelle\.com$/.test(host) && !host.startsWith('api.')) {
    problem = 'points at the website itself; Vercel only hosts the UI, so there is no API there';
  }
  if (problem) {
    console.error(
      `API_URL ("${apiUrl}") ${problem}.\n` +
      `Set API_URL in Vercel (Settings → Environment Variables) to the deployed API, e.g. https://<api-host>/api/v1, then redeploy.`
    );
    process.exit(1);
  }
}

const contents = `// AUTO-GENERATED by scripts/generate-env.js from ${files.envFile} — do not edit by hand, do not commit.
export const environment = {
  production: ${target === 'production'},
  apiUrl: '${process.env.API_URL}', // from API_URL
  // Until these APIs are deployed, their requests stay on the Care API.
  mailsApiUrl: '${process.env.MAILS_API_URL || process.env.API_URL}', // from MAILS_API_URL, else API_URL
  paymentsApiUrl: '${process.env.PAYMENTS_API_URL || process.env.API_URL}', // from PAYMENTS_API_URL, else API_URL
  firebase: {
    apiKey: '${process.env.FIREBASE_API_KEY}', // from FIREBASE_API_KEY
    authDomain: '${process.env.FIREBASE_AUTH_DOMAIN}', // from FIREBASE_AUTH_DOMAIN
    projectId: '${process.env.FIREBASE_PROJECT_ID}', // from FIREBASE_PROJECT_ID
    storageBucket: '${process.env.FIREBASE_STORAGE_BUCKET}', // from FIREBASE_STORAGE_BUCKET
    messagingSenderId: '${process.env.FIREBASE_MESSAGING_SENDER_ID}', // from FIREBASE_MESSAGING_SENDER_ID
    appId: '${process.env.FIREBASE_APP_ID}' // from FIREBASE_APP_ID
  }
};
`;

fs.writeFileSync(path.join(__dirname, '..', 'src', 'environments', files.output), contents);
console.log(`Generated ${files.output} from ${files.envFile}`);
