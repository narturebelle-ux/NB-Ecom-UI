// Writes src/environments/environment.<target>.ts from process.env, which
// dotenv-cli has already populated from .env.staging / .env.production.
// Run via `npm run build:staging` / `npm run build:prod` — not meant to be
// called directly. The output file is gitignored and never committed; the
// required shape/keys are documented in .env.staging.example / .env.production.example.
const fs = require('fs');
const path = require('path');

const target = process.argv[2]; // 'staging' | 'production'
const files = {
  staging: { output: 'environment.staging.ts', envFile: '.env.staging' },
  production: { output: 'environment.prod.ts', envFile: '.env.production' }
}[target];

if (!files) {
  console.error(`Unknown target "${target}". Expected "staging" or "production".`);
  process.exit(1);
}

const required = [
  'API_URL',
  'FIREBASE_API_KEY',
  'FIREBASE_AUTH_DOMAIN',
  'FIREBASE_PROJECT_ID',
  'FIREBASE_STORAGE_BUCKET',
  'FIREBASE_MESSAGING_SENDER_ID',
  'FIREBASE_APP_ID'
];

const missing = required.filter(key => !process.env[key]);
if (missing.length) {
  console.error(
    `Missing env vars for "${target}" build: ${missing.join(', ')}\n` +
    `Copy ${files.envFile}.example to ${files.envFile} and fill them in.`
  );
  process.exit(1);
}

// Production must never silently ship with the local-dev mock Firebase config —
// that config is what makes FirebaseAuthService fall into its dev-simulation mode
// (fake users, OTP always "123456"), which would be a real-world auth bypass in prod.
const KNOWN_PLACEHOLDER_KEYS = ['YOUR_FIREBASE_API_KEY'];
if (target === 'production' && KNOWN_PLACEHOLDER_KEYS.includes(process.env.FIREBASE_API_KEY)) {
  console.error(
    `FIREBASE_API_KEY in .env.production is still the placeholder value ("${process.env.FIREBASE_API_KEY}").\n` +
    `Production builds must use a real Firebase project's Web SDK config — see .env.production.example.`
  );
  process.exit(1);
}

const contents = `// AUTO-GENERATED by scripts/generate-env.js from ${files.envFile} — do not edit by hand, do not commit.
export const environment = {
  production: ${target === 'production'},
  apiUrl: '${process.env.API_URL}', // from API_URL
  firebase: {
    apiKey: '${process.env.FIREBASE_API_KEY}', // from FIREBASE_API_KEY
    authDomain: '${process.env.FIREBASE_AUTH_DOMAIN}', // from FIREBASE_AUTH_DOMAIN
    projectId: '${process.env.FIREBASE_PROJECT_ID}', // from FIREBASE_PROJECT_ID
    storageBucket: '${process.env.FIREBASE_STORAGE_BUCKET}', // from FIREBASE_STORAGE_BUCKET
    messagingSenderId: '${process.env.FIREBASE_MESSAGING_SENDER_ID}', // from FIREBASE_MESSAGING_SENDER_ID
    appId: '${process.env.FIREBASE_APP_ID}' // from FIREBASE_APP_ID
  }
};
`;

fs.writeFileSync(path.join(__dirname, '..', 'src', 'environments', files.output), contents);
console.log(`Generated ${files.output} from ${files.envFile}`);
